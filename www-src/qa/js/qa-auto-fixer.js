/**
 * PIV QA Auto-Fixer v4.2.0-R300
 * Detects common symbol rendering issues and applies automatic fixes.
 * Works in conjunction with the QA monitor in app.js.
 */
(function () {
  'use strict';

  var _fixRegistry = {};
  var _fixLog = [];
  var MAX_LOG = 50;

  function registerFix(pattern, fixFn) {
    _fixRegistry[pattern] = fixFn;
  }

  function tryAutoFix(errorMsg, context) {
    var fixed = false;
    for (var pattern in _fixRegistry) {
      if (new RegExp(pattern, 'i').test(errorMsg)) {
        try {
          _fixRegistry[pattern](context);
          _fixLog.push({
            timestamp: Date.now(),
            pattern: pattern,
            symbol: context.symbol || 'unknown',
            error: errorMsg,
            status: 'fixed'
          });
          fixed = true;
        } catch (e) {
          _fixLog.push({
            timestamp: Date.now(),
            pattern: pattern,
            symbol: context.symbol || 'unknown',
            error: errorMsg,
            status: 'fix-failed',
            reason: e.message
          });
        }
      }
    }
    if (_fixLog.length > MAX_LOG) _fixLog = _fixLog.slice(-MAX_LOG);
    return fixed;
  }

  // Built-in fix: Missing jQuery widget — re-install factory
  registerFix('widget.*not.*function|safeWidget.*undefined', function (ctx) {
    if (window.__installWidgetFactory && window.jQuery) {
      window.__installWidgetFactory(window.jQuery);
    }
  });

  // Built-in fix: Missing scope digest
  registerFix('digest.*not.*function|\\$apply.*not.*function', function (ctx) {
    if (ctx.scope && !ctx.scope.$digest) {
      ctx.scope.$digest = function () {};
      ctx.scope.$apply = function (fn) { if (fn) fn(); };
    }
  });

  // Built-in fix: Template not found — inject placeholder via DOM
  registerFix('template.*not found|template.*undefined', function (ctx) {
    if (ctx.element) {
      while (ctx.element.firstChild) ctx.element.removeChild(ctx.element.firstChild);
      var div = document.createElement('div');
      div.style.cssText = 'padding:20px;text-align:center;color:#aaa;';
      var icon = document.createElement('div');
      icon.style.fontSize = '24px';
      icon.textContent = '\u2699';
      var label = document.createElement('div');
      label.textContent = ctx.symbol || 'Symbol';
      var sub = document.createElement('div');
      sub.style.fontSize = '11px';
      sub.textContent = 'Template loading...';
      div.appendChild(icon);
      div.appendChild(label);
      div.appendChild(sub);
      ctx.element.appendChild(div);
    }
  });

  // Built-in fix: Data format mismatch
  registerFix('cannot read.*value|data.*undefined|rows.*not.*iterable', function (ctx) {
    if (ctx.scope) {
      if (!ctx.scope.data) ctx.scope.data = {};
      if (!ctx.scope.value) ctx.scope.value = 0;
      if (!ctx.scope.rows) ctx.scope.rows = [];
    }
  });

  var _api = {
    registerFix: registerFix,
    tryAutoFix: tryAutoFix,
    loadRegistry: function () {
      // Returns a resolved promise with registry info for emulator compatibility
      return Promise.resolve({ fixes: Object.keys(_fixRegistry) });
    },
    getLog: function () { return _fixLog.slice(); },
    getFixLog: function () { return _fixLog.slice(); }, // alias used by emu-guardian
    getFixCount: function () { return _fixLog.filter(function (f) { return f.status === 'fixed'; }).length; },
    clearLog: function () { _fixLog.length = 0; },
    // Stubs for methods called by app.js that don't have full implementations yet
    scanAndFix: function (html, filename) {
      // Scan HTML template for known issues and return fix result
      return { applied: [], html: html };
    },
    fixScope: function (scope, symName) {
      // Ensure scope has required Angular-like methods
      if (scope && !scope.$digest) {
        scope.$digest = function () {};
        scope.$apply = function (fn) { if (fn) fn(); };
      }
    },
    rebindClickHandlers: function (elem, scope) {
      // Re-bind any ng-click style handlers after DOM manipulation
      // No-op in emulator — symbols handle their own events
    },
    emitBusDemoData: function (scope, symName, bus) {
      // Emit demo data through the event bus for simulation mode
      // No-op — demo data is generated by app.js _emitDemoData
    }
  };

  window.__PIV_AUTO_FIXER = _api;
  // Alias for emulator/index.html compatibility
  window.QAAutoFixer = _api;

  console.log('[PIV] QA Auto-Fixer loaded — ' + Object.keys(_fixRegistry).length + ' fix patterns registered');
})();
